// Generates 30 days of realistic trend data for Recharts
export const GENERATE_30_DAYS_ANALYTICS = (): AnalyticsTrendPoint[] => {
  const points: AnalyticsTrendPoint[] = [];
  const today = new Date('2026-10-08T00:00:00Z');

  for (let i = 29; i >= 0; i--) {
    const d = new Date(today);
    d.setDate(d.getDate() - i);
    const dayName = d.toLocaleDateString('en-US', { weekday: 'short' });
    const dateStr = d.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });

    // Weekend vs weekday subtle differences
    const isWeekend = dayName === 'Sat' || dayName === 'Sun';
    const basePrepared = isWeekend ? 440 + ((i * 7) % 60) : 510 + ((i * 11) % 50);
    const baseConsumed = Math.round(basePrepared * (isWeekend ? 0.84 : 0.87) + ((i * 5) % 25));
    const surplus = basePrepared - baseConsumed;
    const rescued = Math.round(surplus * 0.91 + ((i * 3) % 8));

    points.push({
      day: dayName,
      date: dateStr,
      prepared: basePrepared,
      consumed: baseConsumed,
      surplus: Math.max(0, surplus),
      rescued: Math.min(surplus, Math.max(0, rescued)),
    });
  }

  return points;
};

// Convert x,y grid coordinates or lat/lng to exact GPS coordinates
export const toLatLng = (coords?: { x?: number; y?: number; lat?: number; lng?: number }): { lat: number; lng: number } => {
  if (coords?.lat && coords?.lng) {
    return { lat: coords.lat, lng: coords.lng };
  }
  const x = coords?.x ?? 50;
  const y = coords?.y ?? 50;
  // San Francisco Bay Area bounding box conversion
  const lat = 37.74 + ((100 - y) / 100) * 0.07;
  const lng = -122.45 + (x / 100) * 0.07;
  return { lat, lng };
};
